"""Build synthetic PE images and run an end-to-end self test.

Nothing here touches a real executable: the fixtures are generated byte by
byte, which is exactly how the test suite proves the whole pipeline on any OS
(no Windows, no sample binaries, no licence questions).
"""

from __future__ import annotations

import os
import shutil
import struct
import sys
import tempfile
import traceback
from typing import Dict, List, Optional, Tuple

FILE_ALIGN = 0x200
SECT_ALIGN = 0x1000


def _pad_len(size: int, align: int) -> int:
    rem = size % align
    return size if rem == 0 else size + (align - rem)


def _pad(data: bytes, align: int, fill: bytes = b"\0") -> bytes:
    rem = len(data) % align
    return data if rem == 0 else data + fill * (align - rem)


def build_pe(sections: List[Tuple[str, bytes, int]], is_64: bool = True,
             entrypoint_rva: int = 0x1000, machine: Optional[int] = None,
             subsystem: int = 3, timestamp: int = 0x5F000000,
             image_base: Optional[int] = None, checksum: bool = True,
             dll: bool = False,
             relocs: Optional[List[Tuple[int, int]]] = None,
             with_reloc_section: Optional[bool] = None) -> bytes:
    """Return a syntactically valid PE image.

    ``sections`` is a list of ``(name, data, characteristics)``.
    ``relocs`` is a list of ``(rva, type)`` entries; when given (or when
    ``with_reloc_section`` is true) a real ``.reloc`` section and data-directory
    entry are emitted.
    """
    reloc_blob = b""
    sections = list(sections)
    if relocs or with_reloc_section:
        reloc_blob = _build_reloc_blob(relocs or [],
                                       base_rva=0x1000 * (len(sections) + 1))
        sections.append((".reloc", reloc_blob, RDATA_CHARS))

    machine = machine if machine is not None else (0x8664 if is_64 else 0x14C)
    image_base = image_base if image_base is not None else (0x140000000 if is_64 else 0x400000)
    opt_size = 0xF0 if is_64 else 0xE0
    dos = bytearray(0x40)
    dos[0:2] = b"MZ"
    struct.pack_into("<I", dos, 0x3C, 0x40)
    stub = b"\x0e\x1f\xba\x0e\x00\xb4\x09\xcd\x21\xb8\x01\x4c\xcd\x21This program cannot be run in DOS mode.\r\r\n$"
    fat_off = 0x40 + len(stub)
    fat_off = (fat_off + 15) & ~15
    headers = bytearray(fat_off)
    headers[0:0x40] = dos
    headers[0x40:0x40 + len(stub)] = stub
    struct.pack_into("<I", headers, 0x3C, fat_off)
    headers += b"PE\0\0"

    coff = struct.pack(
        "<HHIIIHH", machine, len(sections), timestamp, 0, 0, opt_size,
        0x0022 | (0x2000 if dll else 0x0002))
    headers += coff

    header_size = _pad_len(fat_off + 4 + 20 + opt_size + 40 * len(sections), FILE_ALIGN)
    raw_ptr = header_size
    sec_headers = b""
    blobs: List[bytes] = []
    for name, data, chars in sections:
        raw = _pad(bytes(data), FILE_ALIGN)
        vaddr = 0x1000 * (len(blobs) + 1)
        sec_headers += struct.pack("<8sIIIIIIHHI", name.encode()[:8].ljust(8, b"\0"),
                                   len(data), vaddr, len(raw), raw_ptr, 0, 0, 0, 0, chars)
        blobs.append((raw, raw_ptr))
        raw_ptr += len(raw)
    image_size = (len(blobs) + 1) * SECT_ALIGN

    opt = bytearray(opt_size)
    if is_64:
        struct.pack_into("<H", opt, 0, 0x20B)
        struct.pack_into("<I", opt, 16, entrypoint_rva)
        struct.pack_into("<I", opt, 20, 0x1000)
        struct.pack_into("<Q", opt, 24, image_base)
        struct.pack_into("<I", opt, 32, SECT_ALIGN)
        struct.pack_into("<I", opt, 36, FILE_ALIGN)
        struct.pack_into("<I", opt, 56, image_size)
        struct.pack_into("<I", opt, 60, header_size)
        struct.pack_into("<H", opt, 68, subsystem)
        struct.pack_into("<I", opt, 108, 16)
        struct.pack_into("<H", opt, 0x46, 0x0100)  # MajorSubsystemVersion 1
    else:
        struct.pack_into("<H", opt, 0, 0x10B)
        struct.pack_into("<I", opt, 16, entrypoint_rva)
        struct.pack_into("<I", opt, 20, 0x1000)
        struct.pack_into("<I", opt, 28, image_base)
        struct.pack_into("<I", opt, 32, SECT_ALIGN)
        struct.pack_into("<I", opt, 36, FILE_ALIGN)
        struct.pack_into("<I", opt, 56, image_size)
        struct.pack_into("<I", opt, 60, header_size)
        struct.pack_into("<H", opt, 68, subsystem)
        struct.pack_into("<I", opt, 92, 16)
        struct.pack_into("<H", opt, 0x46, 0x0100)
    struct.pack_into("<I", opt, 0x38, 0x100000)   # SizeOfStackReserve
    if reloc_blob:
        dirs_off = (112 if is_64 else 96) + 5 * 8
        struct.pack_into("<II", opt, dirs_off,
                         0x1000 * len(sections), len(reloc_blob))
    headers += bytes(opt) + sec_headers

    image = bytearray(_pad(bytes(headers), FILE_ALIGN))
    assert len(image) == header_size, (len(image), header_size)
    for raw, _off in blobs:
        image += raw
    out = bytes(image)

    if checksum:
        csum = _pe_checksum(out)
        csum_off = fat_off + 24 + 64
        out = out[:csum_off] + struct.pack("<I", csum) + out[csum_off + 4:]
    return out


def _build_reloc_blob(entries: List[Tuple[int, int]], base_rva: int) -> bytes:
    """Group ``(rva, type)`` entries into relocation blocks, 4-byte aligned."""
    if not entries:
        return b"\0\0\0\0\0\0\0\0"
    pages: Dict[int, List[int]] = {}
    for rva, typ in entries:
        pages.setdefault(rva & 0xFFFFF000, []).append(((typ << 12) | (rva & 0xFFF)))
    out = bytearray()
    for page in sorted(pages):
        words = pages[page]
        while len(words) % 2:            # pad to a 4-byte boundary
            words.append(0)              # type 0 == ABOLUTE, ignored
        size = 8 + len(words) * 2
        out += struct.pack("<II", page, size)
        for word in words:
            out += struct.pack("<H", word)
    return bytes(out)


def _pe_checksum(data: bytes) -> int:
    lfanew = struct.unpack_from("<I", data, 0x3C)[0]
    csum_off = lfanew + 24 + 64
    total = 0
    for i in range(0, len(data), 2):
        if csum_off <= i < csum_off + 4:
            continue
        hi = data[i + 1] if i + 1 < len(data) else 0
        total += data[i] | (hi << 8)
        total = (total & 0xFFFF) + (total >> 16)
    total = (total & 0xFFFF) + (total >> 16)
    return (total + len(data)) & 0xFFFFFFFF


TEXT_CHARS = 0x60000020  # CNT_CODE | MEM_EXECUTE | MEM_READ
RDATA_CHARS = 0x40000040  # initialized data | MEM_READ
DATA_CHARS = 0xC0000040   # initialized data | MEM_READ | MEM_WRITE


def sample_app(patch: bool = False, is_64: bool = True, marker: bytes = b"X") -> bytes:
    """A plausible little 'app' with code-looking bytes, strings and a data blob."""
    # fake x64-ish prologue / calls, with junk in between so anchors are unique
    code = bytearray()
    code += bytes.fromhex("48894C2408574883EC20488B01FF5028")
    code += bytes.fromhex("8B0D" + "A1A2A3A4" + "85C9")
    code += b"\x74\x18" + bytes.fromhex("488D0D" + "10203040")
    code += b"SurrealismWindow\0"
    code += bytes.fromhex("4883C4205FC3CCCCCCCC")
    code += bytes.fromhex("E8" + "0A0B0C0D" + "4885C0")
    code += b"\x0F\x84" + bytes.fromhex("90706050")
    code += bytes.fromhex("488D15" + "F0E0D0C0")
    if patch:
        # a *single* 4-byte constant changes: the classic "is_trial = 1" edit
        code += b"\x7E\x0F"  # jle short +15   (was jg)
        code += bytes.fromhex("B801000000")  # mov eax, 1
    else:
        code += b"\x7F\x0F"  # jg short +15
        code += bytes.fromhex("B801000000")
    code += bytes.fromhex("4883EC08E8" + "11223344" + "4883C408C3")
    code = _pad(bytes(code), 0x10)

    rdata = b"Version 1.0.0 build 2026-11-01\0"
    rdata += b"Surrealism Window example binary \xef\xbf\xbd demo\0"
    nag = b"Trial expired. Activate to continue.\0"
    # same length on purpose: format v1 only supports size-preserving edits
    rdata += nag if not patch else b"\0" * len(nag)
    rdata += b"settings.ini\0locale\0"
    rdata = _pad(rdata, 0x10)

    data = bytearray(b"CFG=")
    data += b"\x00SURREAL" + bytes(range(64))
    data = _pad(bytes(data), 0x10)

    return build_pe([(".text", code, TEXT_CHARS),
                     (".rdata", rdata, RDATA_CHARS),
                     (".data", data, DATA_CHARS)], is_64=is_64)


def make_pe_pair(tmpdir: str, is_64: bool = True) -> Tuple[str, str]:
    old = os.path.join(tmpdir, "demo_app.exe")
    new = os.path.join(tmpdir, "demo_app_patched.exe")
    with open(old, "wb") as fh:
        fh.write(sample_app(patch=False, is_64=is_64))
    with open(new, "wb") as fh:
        fh.write(sample_app(patch=True, is_64=is_64))
    return old, new


