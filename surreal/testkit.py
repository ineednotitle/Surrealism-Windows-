def run_selftest(keep: bool = False, workdir: Optional[str] = None,
                 verbose: bool = False) -> Tuple[bool, List[str]]:
    """Exercise build → diff → check → apply → revert on a synthetic PE."""
    from . import diffgen, patcher
    from .journal import Journal
    from .patchfile import Bundle
    from .pe import PE
    from .util import sha256_file

    report: List[str] = []
    ok = True
    base = workdir or tempfile.mkdtemp(prefix="surreal-selftest-")
    os.makedirs(base, exist_ok=True)
    base_dir = base

    def step(name: str, fn) -> None:
        nonlocal ok
        try:
            detail = fn()
            report.append("PASS  %-42s %s" % (name, detail or ""))
        except Exception as exc:  # noqa: BLE001 - selftest reports everything
            ok = False
            report.append("FAIL  %-42s %s: %s" % (name, type(exc).__name__, exc))

    try:
        old, new = make_pe_pair(base)

        def _parse():
            with PE.open(old) as pe:
                return "%d sections, entry 0x%X, checksum %s" % (
                    len(pe.sections), pe.entrypoint_rva,
                    "valid" if pe.checksum_valid() else "STALE")

        step("parse synthetic PE", _parse)

        bundle_path = os.path.join(base, "demo.morph")
        info: Dict[str, object] = {}

        def _diff():
            bundle, stats = diffgen.build_bundle(old, new, "org.surreal.demo",
                                                 "Demo patch", author="selftest")
            bundle.save(bundle_path)
            info["hunks"] = len(bundle.hunks)
            return "%d hunk(s), %d anchored" % (len(bundle.hunks), stats["anchored"])

        step("diff two builds → bundle", _diff)

        def _check():
            bundle = Bundle.load(bundle_path)
            plan = patcher.build_plan(bundle, old)
            return "%d hunk(s) resolved" % len(plan.resolved)

        step("preflight resolves every hunk", _check)

        def _bad_target():
            evil = os.path.join(base, "other.exe")
            with open(evil, "wb") as fh:
                fh.write(sample_app(patch=False, is_64=False))
            bundle = Bundle.load(bundle_path)
            try:
                patcher.build_plan(bundle, evil)
            except patcher.PatchError:
                return "wrong target rejected"
            raise AssertionError("wrong target was accepted!")

        step("wrong target is rejected", _bad_target)

        before = sha256_file(old)

        def _apply():
            bundle = Bundle.load(bundle_path)
            res = patcher.apply_bundle(bundle, old)
            return "sha %s… → %s…" % (before[:8], res["sha256_after"][:8])

        step("apply (backup + atomic swap)", _apply)

        def _verify_patched():
            expected = sha256_file(new)
            got = sha256_file(old)
            if got != expected:
                raise AssertionError("patched file does not match the reference build")
            with PE.open(old) as pe:
                if not pe.checksum_valid():
                    raise AssertionError("checksum not recomputed")
            return "byte-identical to the reference build, checksum valid"

        step("result equals reference build", _verify_patched)

        def _revert():
            res = patcher.revert(old)
            if sha256_file(old) != before:
                raise AssertionError("revert did not restore the original")
            return "restored %s…" % res["restored_sha256"][:8]

        step("revert restores the original", _revert)

        def _journal():
            j = Journal(old)
            actions = [e["action"] for e in j.entries]
            if actions != ["apply", "revert"]:
                raise AssertionError("unexpected journal: %r" % actions)
            return "journal: " + " → ".join(actions)

        step("journal records both actions", _journal)

        def _sign_and_verify():
            from . import keys

            key_path = os.path.join(base, "selftest.key")
            record = keys.generate_key_file(key_path, signer="selftest")
            bundle = Bundle.load(bundle_path)
            raw = keys.sign_bundle(bundle.to_dict(),
                                   bytes.fromhex(record["private_seed"]),
                                   signer="selftest")
            import json as _json

            with open(bundle_path, "w", encoding="utf-8") as fh:
                _json.dump(raw, fh, indent=2)
            block = keys.verify_bundle(raw)
            if block["public_key"] != record["public_key"]:
                raise AssertionError("signature key mismatch")
            return "ed25519 signature verifies (%s…)" % block["public_key"][:12]

        step("sign + verify a bundle", _sign_and_verify)

        def _tamper_detected():
            import json as _json

            from . import keys

            with open(bundle_path, "r", encoding="utf-8") as fh:
                raw = _json.load(fh)
            raw["hunks"][0]["replace"] = "90"
            try:
                keys.verify_bundle(raw)
            except keys.SignatureError:
                return "edited bundle rejected"
            raise AssertionError("tampered bundle verified!")

        step("tampered bundle is rejected", _tamper_detected)

        def _lock():
            from .lock import LockError, TargetLock

            lock = TargetLock(old, action="selftest").acquire()
            try:
                try:
                    TargetLock(old, action="selftest").acquire()
                except LockError:
                    return "second holder refused"
                raise AssertionError("lock did not exclude a second holder")
            finally:
                lock.release()

        step("apply lock excludes a second holder", _lock)

        def _overlay_append():
            with open(old, "rb") as fh:
                base = fh.read()
            grown = os.path.join(base_dir, "demo_overlay.exe")
            payload = b"[overlay]appended-by-selftest\r\n"
            with open(grown, "wb") as fh:
                fh.write(base + payload)
            ob, _ = diffgen.build_bundle(old, grown, "org.surreal.selftest.overlay",
                                         "overlay")
            if [h.op for h in ob.hunks] != ["append"]:
                raise AssertionError("expected exactly one append hunk, got %r"
                                     % [h.op for h in ob.hunks])
            path = os.path.join(base_dir, "overlay.morph")
            ob.save(path)
            res = patcher.apply_bundle(Bundle.load(path), old)
            if res["size_after"] != os.path.getsize(grown):
                raise AssertionError("append did not grow the file")
            patcher.revert(old)
            if os.path.getsize(old) != os.path.getsize(grown) - len(payload):
                raise AssertionError("revert did not restore the size")
            return "append +%d bytes, revert restored the size" % len(payload)

        step("overlay size change (append + revert)", _overlay_append)

        def _extend_section():
            import struct

            from . import surgery

            grown = os.path.join(base_dir, "grown_section.exe")
            shutil.copyfile(old, grown)
            pe = PE.open(grown)
            try:
                plan = surgery.plan_extend_section(pe, pe.sections[-1].name,
                                                   b"SELFTEST-EXTRA-SECTION-DATA")
            finally:
                pe.close()
            with open(grown, "r+b") as fh:
                for offset, data in plan.writes:
                    fh.seek(offset)
                    fh.write(data)
                fh.seek(0, os.SEEK_END)
                fh.write(plan.payload)
            with PE.open(grown) as after:
                csum, skip = after.compute_checksum(), after._checksum_offset
            with open(grown, "r+b") as fh:
                fh.seek(skip)
                fh.write(struct.pack("<I", csum))

            eb, _ = diffgen.build_bundle(old, grown, "org.surreal.selftest.extend",
                                         "extend-section")
            if [h.op for h in eb.hunks] != ["extend-section"]:
                raise AssertionError("generator did not produce extend-section: %r"
                                     % [h.op for h in eb.hunks])
            path = os.path.join(base_dir, "extend.morph")
            eb.save(path)
            patcher.apply_bundle(Bundle.load(path), old)
            with open(old, "rb") as a, open(grown, "rb") as b:
                if a.read() != b.read():
                    raise AssertionError("extend-section did not reproduce the build")
            patcher.revert(old)
            return "extend-section reproduces the reference build"

        step("image surgery (extend-section)", _extend_section)

        def _collection():
            import json as _json

            from . import collection as coll

            with open(old, "rb") as fh:
                base_bytes = fh.read()
            versioned = bytearray(base_bytes)
            needle = b"Version 1.0.0 build 2026-11-01"
            at = bytes(versioned).find(needle)
            if at < 0:
                raise AssertionError("fixture lost its version string")
            versioned[at:at + len(needle)] = b"\0" * len(needle)
            mod = os.path.join(base_dir, "noversion.exe")
            with open(mod, "wb") as fh:
                fh.write(bytes(versioned))
            vb, _ = diffgen.build_bundle(old, mod, "org.surreal.selftest.version",
                                         "version")
            vb.save(os.path.join(base_dir, "version.morph"))
            nag = Bundle.load(bundle_path)
            if nag.signature:
                # the signed bundle from the previous step is fine too
                pass
            manifest = {
                "format": "surreal.collection", "format_version": 1,
                "name": "selftest set",
                "patches": [
                    {"bundle": os.path.basename(bundle_path), "order": 10},
                    {"bundle": "version.morph", "order": 20},
                ],
            }
            mpath = os.path.join(base_dir, "surreal-collection.json")
            with open(mpath, "w", encoding="utf-8") as fh:
                _json.dump(manifest, fh, indent=2)
            c = coll.load_collection(base_dir)
            before = sha256_file(old)
            res = coll.apply_collection(c, old)
            if len(res["applied"]) != 2:
                raise AssertionError("expected 2 patches, applied %d"
                                     % len(res["applied"]))
            patcher.revert(old)
            if sha256_file(old) != before:
                raise AssertionError("collection revert did not restore the file")
            return "2 patches applied as one transaction, revert restored"

        step("collection apply + revert (transactional)", _collection)

        def _vault():
            import json as _json

            from . import collection as coll

            vaultdir = os.path.join(base, "vault")
            os.makedirs(vaultdir, exist_ok=True)
            appdir = os.path.join(base, "app")
            os.makedirs(appdir, exist_ok=True)
            main = os.path.join(appdir, "main.exe")
            shutil.copyfile(old, main)
            helper_bytes = build_pe([(".text", b"\x90" * 0x100, 0x60000020),
                                     (".rdata", b"helper-strings\0" * 8, 0x40000040)])
            helper = os.path.join(appdir, "helper.dll")
            with open(helper, "wb") as fh:
                fh.write(helper_bytes)

            with open(main, "rb") as fh:
                main_bytes = fh.read()
            fixed_main = os.path.join(base, "main_fixed.exe")
            data = bytearray(main_bytes)
            data[0x251] = 0x7E          # same edit the demo bundle makes
            with open(fixed_main, "wb") as fh:
                fh.write(bytes(data))
            mb, _ = diffgen.build_bundle(main, fixed_main,
                                         "org.surreal.selftest.vault-main", "vault-main")
            mb.save(os.path.join(vaultdir, "vault-main.morph"))

            fixed_helper = os.path.join(base, "helper_fixed.dll")
            payload = bytearray(helper_bytes)
            at = bytes(payload).find(b"helper-strings")
            payload[at:at + len(b"helper-strings")] = b"VAULT-STRINGS!"
            with open(fixed_helper, "wb") as fh:
                fh.write(bytes(payload))
            hb, _ = diffgen.build_bundle(helper, fixed_helper,
                                         "org.surreal.selftest.vault-helper",
                                         "vault-helper")
            hb.save(os.path.join(vaultdir, "vault-helper.morph"))

            manifest = {
                "format": "surreal.collection", "format_version": 1,
                "name": "selftest vault",
                "patches": [
                    {"bundle": "vault-main.morph", "target": "main.exe", "order": 10},
                    {"bundle": "vault-helper.morph", "target": "helper.dll",
                     "order": 20},
                ],
            }
            mpath = os.path.join(vaultdir, "surreal-repo.json")
            with open(mpath, "w", encoding="utf-8") as fh:
                _json.dump(manifest, fh, indent=2)
            c = coll.load_collection(vaultdir)
            if not c.is_vault or len(c.files()) != 2:
                raise AssertionError("vault loading did not group two files")
            before = (sha256_file(main), sha256_file(helper))
            res = coll.apply_vault(c, appdir)
            if len(res["files"]) != 2:
                raise AssertionError("expected 2 files, patched %d" % len(res["files"]))
            for path in (main, helper):
                patcher.revert(path)
            if (sha256_file(main), sha256_file(helper)) != before:
                raise AssertionError("vault rollback/revert did not restore both files")
            return "2 files patched in one transaction, both reverted"

        step("vault apply + per-file revert (multi-file)", _vault)

        def _repo():
            from . import repo as _repo

            repodir = os.path.join(base, "repodir")
            os.makedirs(repodir, exist_ok=True)
            shutil.copyfile(bundle_path, os.path.join(repodir, "nag.morph"))
            index = _repo.build_index(repodir, name="selftest repo",
                                      base_dir=repodir)
            idx_path = os.path.join(repodir, "surreal-repo.json")
            _repo.write_index(index, idx_path)
            loaded = _repo.load_index(idx_path)
            matches = _repo.matching(loaded, old)
            if not matches:
                raise AssertionError("repo index did not match the fixture")
            entry = matches[0]
            rb, path = _repo.load_bundle(loaded, entry)
            if not os.path.isfile(path):
                raise AssertionError("repo resolved a missing bundle")
            before = sha256_file(old)
            patcher.apply_bundle(rb, old)
            patcher.revert(old)
            if sha256_file(old) != before:
                raise AssertionError("repo apply/revert did not restore the file")
            # a bundle edited after indexing must be refused
            with open(os.path.join(repodir, "nag.morph"), "ab") as fh:
                fh.write(b" ")
            try:
                _repo.load_bundle(loaded, entry)
            except _repo.RepoError:
                return "%d bundle(s) indexed, integrity enforced" % len(loaded["bundles"])
            raise AssertionError("stale repo index was accepted")

        step("local patch repo (index + apply)", _repo)

        def _bad_bundle():
            bad = os.path.join(base, "bad.morph")
            with open(bad, "w", encoding="utf-8") as fh:
                fh.write('{"format":"surreal.morph","format_version":1,"id":"x",'
                         '"target":{"filename":"a.exe"},"hunks":[]}')
            try:
                Bundle.load(bad)
            except Exception as exc:  # noqa: BLE001
                return "invalid bundle rejected (%s)" % type(exc).__name__
            raise AssertionError("invalid bundle was accepted")

        step("malformed bundle rejected", _bad_bundle)
    except BaseException as exc:  # noqa: BLE001 - a crash must be reported, not hidden
        ok = False
        report.append("FAIL  %-42s %s: %s"
                      % ("selftest aborted", type(exc).__name__, exc))
        for line in traceback.format_exc().strip().splitlines():
            report.append("      " + line)
    finally:
        if keep:
            report.append("workspace kept at %s" % base)
        else:
            shutil.rmtree(base, ignore_errors=True)
    return ok, report


if __name__ == "__main__":  # pragma: no cover
    good, lines = run_selftest(keep="--keep" in sys.argv)
    print("\n".join(lines))
    sys.exit(0 if good else 1)
